import nodemailer from 'nodemailer';
import { createInvoicePdf } from '../pdf/invoice-pdf.js';
import { companyEmailFrom, companyInfo, displayId, displayIdNumber } from '@seferbiz/company';

let transporter;

function getTransporter() {
  if (!process.env.SMTP_HOST) {
    throw new Error('Invoice email delivery is not configured (SMTP_HOST is required)');
  }
  if (!transporter) {
    const port = Number(process.env.SMTP_PORT || 587);
    transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port,
      secure: process.env.SMTP_SECURE === 'true' || port === 465,
      ...(process.env.SMTP_USER ? {
        auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASSWORD || '' }
      } : {})
    });
  }
  return transporter;
}

export async function sendInvoiceEmail({ invoice, client, lines }, transport) {
  const recipient = client.email || client.email_accounting;
  if (!recipient) throw new Error('The client does not have a billing email address');
  const ownerContact = `${companyInfo.personMain.first_name} ${companyInfo.personMain.last_name} <${companyInfo.personMain.email}>`;

  const currency = invoice.currency || 'USD';
  const total = Number(invoice.cost ?? invoice.total ?? 0).toFixed(2);
  const lineDetails = lines.map((line) => {
    const amount = Number(line.total ?? line.amount ?? 0).toFixed(2);
    const quantity = line.hours ? ` (${line.hours} hours${line.rate ? ` at ${currency} ${line.rate}/hour` : ''})` : '';
    return `- ${line.description || 'Invoice item'}${quantity}: ${currency} ${amount}`;
  });
  const appUrl = process.env.PUBLIC_APP_URL?.replace(/\/$/, '');
  const invoiceDisplayId = displayId(client?.name, invoice.id);
  const invoiceDisplayNumber = displayIdNumber(invoice.id);
  const invoiceUrl = appUrl
    ? `${appUrl}/invoices/${invoice.id}${invoice.access_token ? `?access_token=${encodeURIComponent(invoice.access_token)}` : ''}`
    : null;
  const clientPortalUrl = appUrl && client?.access_token
    ? `${appUrl}/clients/${client.id}?access_token=${encodeURIComponent(client.access_token)}`
    : null;
  const text = [
    `${companyInfo.name}`,
		``,
		`======`,
		``,
		`Invoice for ${client.name || 'Client'}`,
		`ID: ${invoiceDisplayId}`,
		`Amount: $${total}`,
		`Status: ${invoice.paid ? 'PAID' : 'NOT PAID'}`,
    '',
		`${companyInfo.legalEntity || 'N/A'}`,
		`${companyInfo.address.address1 || 'N/A'}${companyInfo.address.address2 ? ` ${companyInfo.address.address2}` : ''}`,
		`${companyInfo.address.city || 'N/A'}, ${companyInfo.address.state || 'N/A'} ${companyInfo.address.zipcode || 'N/A'}`,
		``,
		`${invoice.description || ''}`,
		``,
		`Attached is an invoice PDF with cost breakdowns and payment information for your records. This payment can be made out to '${companyInfo.legalEntity}'.`,
		``,
    `View Payment Instructions and pay this invoice online: ${invoiceUrl}`,
		``,
    `Payment Terms: ${client.payment_terms || 'Net 15'}`,
		``,
    ...(clientPortalUrl ? [`View all ${client.name || 'Client'} invoices: ${clientPortalUrl}`] : []),
		``,
		`======`,
		``,
		`Note: This email is auto-generated by our invoicing system. If you have questions or find any discrepancies, feel free to contact us.`
  ].join('\n');
  const pdf = await createInvoicePdf({ invoice, client, lines });

  await (transport || getTransporter()).sendMail({
    from: process.env.SMTP_FROM || companyEmailFrom,
    to: recipient,
    replyTo: ownerContact,
    cc: [client.email_accounting_2, client.email_accounting_3].filter(Boolean),
    bcc: [ownerContact],
    subject: `${process.env.NODE_ENV === 'development' ? 'DEV - ' : ''}Invoice from ${companyInfo.name}`,
    text,
    attachments: [{
      filename: `Invoice-${invoiceDisplayNumber}.pdf`,
      content: pdf,
      contentType: 'application/pdf'
    }]
  });
  return { recipient };
}
